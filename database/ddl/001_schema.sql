-- SOBRE O USUARIO "admin"
--
-- Por pedido seu, o admin (acesso do desenvolvedor, mesmo conceito do
-- admin do NF-EntradaSN) NAO tem linha em NENHUMA tabela deste schema:
-- nem em TB_LOCAL_ADMIN_CREDENCIAL, nem em TB_REGRAS_USUARIOS.
--
-- A identidade, o hash da senha e a role ADMIN dele ficam resolvidos
-- inteiramente em codigo + variaveis de ambiente do backend
-- (ADMIN_CODUSUARIO / ADMIN_SENHA_HASH em backend/.env), num unico ponto
-- centralizado (backend/src/modules/auth/auth.service.ts) — diferente do
-- NF-EntradaSN, onde a senha do admin ficou hardcoded em texto puro e
-- espalhada em varios "if username === 'ADMIN'" pelo codigo. Aqui o valor
-- nunca aparece em texto puro em lugar nenhum (nem no .env, so o hash) e a
-- checagem de admin existe em um unico lugar.
